def 検証する(法律文: 法律) -> list:
    警告の並び: list = []

    try:
        範囲外を調べる(法律文)
        型を調べる(法律文)
        品目を調べる(法律文, 警告の並び)
        矛盾を調べる(法律文, 警告の並び)
        財源を調べる(法律文, 警告の並び)
    except 法律エラー as err:
        err.原文 = err.原文 or 法律文.原文
        raise

    for warning in 警告の並び:
        warning.原文 = warning.原文 or 法律文.原文
    return 警告の並び


def 範囲外を調べる(法律文: 法律) -> None:
    for node in 全ノードを辿る(法律文):
        if isinstance(node, 範囲外):
            reason = 断る理由.get(node.語, "この模型に対応する仕組みがありません")
            raise 範囲外エラー(
                f"「{node.語}」は現在のシミュレーション範囲外です",
                node.行, node.桁,
                助言=f"{reason}。実装済みの効果は 税率変更 / 給付 / 禁止 の3つです",
            )

        ir_type = 節とIRの対応.get(type(node))
        if ir_type is not None and ir_type not in 対応プリミティブ:
            raise 範囲外エラー(
                f"この効果({ir_type})はエンジンが対応していません",
                node.行, node.桁,
                助言=f"engine/effects.SUPPORTED = {対応プリミティブ}",
            )

    対象指定 = 法律文.節を探す(対象)
    if 対象指定 is not None and 対象指定.条件 is not None:
        known = 対象ごとの属性[対象指定.対象種別]
        for 比較ひとつ in 対象指定.条件.比較の並び:
            if 比較ひとつ.属性 not in known:
                raise 範囲外エラー(
                    f"{対象指定.対象種別}は「{比較ひとつ.属性}」という属性を持っていません",
                    比較ひとつ.行, 比較ひとつ.桁,
                    助言=f"{対象指定.対象種別}に使えるのは {' / '.join(known)} です",
                )

    for 効果ひとつ in 法律文.効果():
        if isinstance(効果ひとつ, 税率変更) and 効果ひとつ.税 not in 税の一覧:
            raise 範囲外エラー(
                f"「{効果ひとつ.税}」はこの模型に存在しない税です",
                効果ひとつ.行, 効果ひとつ.桁,
                助言=f"変更できるのは {' / '.join(sorted(税の一覧))} です",
            )
        if isinstance(効果ひとつ, 禁止) and 効果ひとつ.対象 != "支出":
            raise 範囲外エラー(
                f"「{効果ひとつ.対象}」を禁止する仕組みがありません",
                効果ひとつ.行, 効果ひとつ.桁,
                助言="禁止できるのは 支出(カテゴリ=…) だけです。"
                     "行動や発言はこの模型に存在しません",
            )


def 全ノードを辿る(法律文: 法律):
    for clause in 法律文.節:
        yield clause
        if isinstance(clause, 効果一覧):
            yield from clause.効果


def 型を調べる(法律文: 法律) -> None:
    対象指定 = 法律文.節を探す(対象)
    if 対象指定 is not None and 対象指定.条件 is not None:
        条件の単位を調べる(対象指定)

    enforce = 法律文.節を探す(執行率)
    if enforce is not None:
        if enforce.割合.単位 != "%":
            raise 検証エラー(
                "執行率は % で書きます", enforce.割合.行, enforce.割合.桁,
                助言="執行率: 80% のように書きます",
            )
        if not 0.0 <= enforce.割合.割合にする() <= 1.0:
            raise 検証エラー(
                f"執行率 {enforce.割合.数}% は 0〜100% の外です",
                enforce.割合.行, enforce.割合.桁,
                助言="執行率は「取り締まりがどれだけ効くか」の割合です。"
                     "100% を超える取り締まりはありません",
            )

    for 効果ひとつ in 法律文.効果():
        if isinstance(効果ひとつ, 税率変更):
            if (効果ひとつ.税, 効果ひとつ.品目) in 金額で書く項目:
                for value, name in ((効果ひとつ.変更前, "変更前"), (効果ひとつ.変更後, "変更後")):
                    if value.単位 not in ("円", "万円"):
                        raise 検証エラー(
                            f"{効果ひとつ.税}の{効果ひとつ.品目}({name})は金額で書きます",
                            value.行, value.桁,
                            助言="税率変更: 相続税(基礎控除) 4200万円 → 1000万円 のように書きます",
                        )
                    if value.数 < 0:
                        raise 検証エラー(
                            "控除額は負にできません", value.行, value.桁)
                continue

            for value, name in ((効果ひとつ.変更前, "変更前"), (効果ひとつ.変更後, "変更後")):
                if value.単位 != "%":
                    raise 検証エラー(
                        f"税率({name})は % で書きます", value.行, value.桁,
                        助言="8% → 0% のように書きます",
                    )
                if value.数 < 0:
                    raise 検証エラー(
                        f"税率に負の値({value.数}%)は指定できません",
                        value.行, value.桁,
                        助言="給付をしたいなら 効果 { 給付: … } を使います",
                    )
        if isinstance(効果ひとつ, 給付):
            if 効果ひとつ.額.単位 != "円":
                raise 検証エラー(
                    "給付額は円で書きます", 効果ひとつ.額.行, 効果ひとつ.額.桁,
                    助言="給付: 15000円/月 のように書きます",
                )
            if 効果ひとつ.額.数 < 0:
                raise 検証エラー(
                    "給付額は負にできません", 効果ひとつ.額.行, 効果ひとつ.額.桁,
                    助言="取り立てたいなら 効果 { 税率変更: … } を使います",
                )
            if 効果ひとつ.掛ける対象 is not None and 効果ひとつ.掛ける対象 not in 対象ごとの属性["世帯"]:
                raise 範囲外エラー(
                    f"「{効果ひとつ.掛ける対象}」で掛けることはできません",
                    効果ひとつ.行, 効果ひとつ.桁,
                    助言=f"使えるのは {' / '.join(対象ごとの属性['世帯'])} です",
                )


def 条件の単位を調べる(対象指定: 対象) -> None:
    known = 対象ごとの属性[対象指定.対象種別]
    for 比較ひとつ in 対象指定.条件.比較の並び:
        want = known[比較ひとつ.属性]
        got = 比較ひとつ.値.単位
        if got is None:
            continue
        if want is None:
            raise 検証エラー(
                f"「{比較ひとつ.属性}」に単位「{got}」は付けられません",
                比較ひとつ.値.行, 比較ひとつ.値.桁,
                助言=f"{比較ひとつ.属性} は個数なので、単位なしで書きます",
            )
        if got != want:
            raise 検証エラー(
                f"「{比較ひとつ.属性}」の単位は「{want}」です。「{got}」は使えません",
                比較ひとつ.値.行, 比較ひとつ.値.桁,
                助言=f"例: {比較ひとつ.属性} {比較ひとつ.演算子} 10{want}",
            )


def 品目を調べる(法律文: 法律, 警告の並び: list) -> None:
    for 効果ひとつ in 法律文.効果():
        name = None
        if isinstance(効果ひとつ, 税率変更):
            if (効果ひとつ.税, 効果ひとつ.品目) in 金額で書く項目 or 効果ひとつ.税 != "消費税":
                continue
            name = 効果ひとつ.品目
        elif isinstance(効果ひとつ, 禁止):
            name = 効果ひとつ.引数.get("カテゴリ")
        if name is None:
            continue

        if isinstance(効果ひとつ, 税率変更) and name == "その他":
            警告の並び.append(警告(
                "「その他」を家計調査の分類「その他」(その他の消費支出)として扱いました",
                効果ひとつ.行, 効果ひとつ.桁,
                助言="「食料以外の全品目」を指すつもりなら、品目を書かずに "
                     "税率変更: 消費税 10% → 12% と書きます。"
                     "この2つは税収が5倍ちがいます",
            ))

        親世帯, 取り分 = 品目名をそろえる(name)
        if 親世帯 not in 品目一覧:
            raise 範囲外エラー(
                f"「{name}」という品目はこの模型にありません",
                効果ひとつ.行, 効果ひとつ.桁,
                助言=f"家計調査の8分類だけを持っています: {' / '.join(品目一覧)}",
            )
        if 取り分 is not None:
            警告の並び.append(品目の警告(name, 効果ひとつ.行, 効果ひとつ.桁))


def 矛盾を調べる(法律文: 法律, 警告の並び: list) -> None:
    既出の税 = {}
    既出の禁止 = {}

    for 効果ひとつ in 法律文.効果():
        if isinstance(効果ひとつ, 税率変更):
            鍵 = (効果ひとつ.税, 品目名をそろえる(効果ひとつ.品目)[0])
            if 鍵 in 既出の税:
                警告の並び.append(警告(
                    f"「{効果ひとつ.税}"
                    f"{'(' + 効果ひとつ.品目 + ')' if 効果ひとつ.品目 else ''}」を"
                    f"1つの法律の中で2回変更しています",
                    効果ひとつ.行, 効果ひとつ.桁,
                    助言=f"後に書いたほう({効果ひとつ.変更後.数}%)が有効になります。"
                         f"{既出の税[鍵]}行目の変更は上書きされます",
                ))
            既出の税[鍵] = 効果ひとつ.行

        if isinstance(効果ひとつ, 禁止):
            鍵 = 品目名をそろえる(効果ひとつ.引数.get("カテゴリ"))[0]
            if 鍵 in 既出の禁止:
                警告の並び.append(警告(
                    f"「{効果ひとつ.引数.get('カテゴリ')}」への禁止が2つあります",
                    効果ひとつ.行, 効果ひとつ.桁,
                    助言="厳しいほうだけが効きます。1つにまとめたほうが読みやすくなります",
                ))
            既出の禁止[鍵] = 効果ひとつ.行


    timing = 法律文.節を探す(施行)
    if timing is not None and timing.施行月数 > 0:
        警告の並び.append(警告(
            f"{timing.施行月数}ヶ月後の施行として扱います",
            timing.行, timing.桁,
            助言="施行前の駆け込み需要は模型化していません。"
                 "施行月にいきなり切り替わります",
        ))


def 品目名をそろえる(name):
    if name is None:
        return None, None
    if name in 内数の品目:
        親世帯, 取り分 = 内数の品目[name]
        return 親世帯, 取り分
    return 品目の別名.get(name, name), None


def 財源を調べる(法律文: 法律, 警告の並び: list) -> None:
    transfers = [e for e in 法律文.効果() if isinstance(e, 給付)]
    if not transfers:
        return

    財源指定 = 法律文.節を探す(財源)

    if 財源指定 is None:
        警告の並び.append(警告(
            "財源が指定されていません。国債発行として扱います",
            transfers[0].行, transfers[0].桁,
            助言="給付した額はそのまま政府債務に積み上がり、"
                 "金利負担が発生します(この模型では債務残高として現れます)。"
                 "財源を付けるなら 財源: 所得税(+1%) のように書きます",
        ))
        return

    if 財源指定.種類 == "税":
        if 財源指定.税 not in 税の一覧:
            raise 範囲外エラー(
                f"「{財源指定.税}」を財源にはできません",
                財源指定.行, 財源指定.桁,
                助言=f"財源にできるのは {' / '.join(sorted(税の一覧))} か 国債 です",
            )
        if 財源指定.今月の増減 is None:
            raise 検証エラー(
                f"「{財源指定.税}」をどれだけ変えるかが書かれていません",
                財源指定.行, 財源指定.桁,
                助言="財源: 所得税(+1%) のように、増減幅を括弧で書きます",
            )
        if 財源指定.今月の増減.単位 != "%":
            raise 検証エラー(
                "財源の増減幅は % で書きます",
                財源指定.今月の増減.行, 財源指定.今月の増減.桁,
                助言="財源: 所得税(+1%)",
            )
    else:
        警告の並び.append(警告(
            "財源を国債と明示しています",
            財源指定.行, 財源指定.桁,
            助言="給付額はそのまま政府債務に積み上がります",
        ))


def 品目の警告(name: str, 行: int, 桁: int):
    親世帯, 取り分 = 品目名をそろえる(name)
    if 取り分 is None:
        return None
    return 警告(
        f"「{name}」は統計にない品目です。{親世帯}の内数({取り分:.0%})として扱います",
        行, 桁,
        助言="家計調査の8分類にカテゴリを増やすと統計の裏付けが無くなるため、"
             "既存カテゴリの一部とみなしています。この比率は設計値で、出典はありません",
    )
